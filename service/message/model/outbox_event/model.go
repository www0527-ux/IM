package outbox_event

import (
	"context"
	"encoding/json"
	"errors"
	"fmt"
	"strings"

	messageevent "infinitechatgo/common/model/event"
	"infinitechatgo/common/txctx"

	"github.com/zeromicro/go-zero/core/stores/sqlx"
)

// AggregateTypeSession marks rows whose aggregate_id is a sessionID.
// MESSAGE_PERSISTED uses it so the relay can find the per-conversation publish
// order through idx_aggregate_seq.
const AggregateTypeSession = "session"

// StatusPending is the outbox state a newly committed event starts in.
const StatusPending = 0

type Model interface {
	InsertPersistedTx(
		ctx context.Context,
		event messageevent.ChatMessagePersistedEvent,
		topic string,
		messageKey string,
	) error
}

type model struct {
	conn sqlx.SqlConn
}

func NewModel(conn sqlx.SqlConn) Model {
	return &model{conn: conn}
}

func (m *model) InsertPersistedTx(
	ctx context.Context,
	event messageevent.ChatMessagePersistedEvent,
	topic string,
	messageKey string,
) error {
	// event_id is the outbox primary key and is not auto-increment, so the
	// writer generates it before the row joins its transaction. Reusing an id
	// that already exists would collide with the primary key.
	if event.EventID <= 0 {
		return errors.New(
			"insert persisted outbox event: event id must be generated by the writer",
		)
	}
	if event.EventType != messageevent.ChatMessagePersistedEventType ||
		event.Version != messageevent.ChatMessageEventVersion {
		return fmt.Errorf(
			"insert persisted outbox event %d: unsupported type %q version %d",
			event.EventID,
			event.EventType,
			event.Version,
		)
	}
	if event.Message.MessageID <= 0 || event.Message.SessionID <= 0 ||
		event.Message.Seq <= 0 {
		return fmt.Errorf(
			"insert persisted outbox event %d: incomplete message message_id=%d session_id=%d seq=%d",
			event.EventID,
			event.Message.MessageID,
			event.Message.SessionID,
			event.Message.Seq,
		)
	}
	if strings.TrimSpace(topic) == "" || strings.TrimSpace(messageKey) == "" {
		return fmt.Errorf(
			"insert persisted outbox event %d: topic and message key are required",
			event.EventID,
		)
	}

	payload, err := json.Marshal(event)
	if err != nil {
		return fmt.Errorf(
			"encode persisted outbox event %d: %w",
			event.EventID,
			err,
		)
	}

	conn, err := txctx.SessionConn(ctx)
	if err != nil {
		return fmt.Errorf(
			"insert persisted outbox event %d: %w",
			event.EventID,
			err,
		)
	}

	// aggregate_id and message_key are the sessionID, aggregate_seq is the
	// message Seq. The row starts at status 0 (PENDING): the relay owns every
	// later transition and only writes PUBLISHED after the broker acknowledges.
	const query = `
INSERT INTO outbox_event
    (event_id, event_type, aggregate_type, aggregate_id, aggregate_seq,
     topic, message_key, payload, status)
VALUES (?, ?, ?, ?, ?, ?, ?, ?, 0)`

	if _, err := conn.ExecCtx(
		ctx,
		query,
		event.EventID,
		event.EventType,
		AggregateTypeSession,
		event.Message.SessionID,
		event.Message.Seq,
		topic,
		messageKey,
		string(payload),
	); err != nil {
		return fmt.Errorf(
			"insert persisted outbox event %d: %w",
			event.EventID,
			err,
		)
	}
	return nil
}
