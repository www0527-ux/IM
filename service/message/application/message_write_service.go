package application

import (
	"context"
	"errors"
	"fmt"
	"strings"

	"infinitechatgo/common/messagecache"
	"infinitechatgo/common/messageidentity"
	messageevent "infinitechatgo/common/model/event"
)

var (
	ErrPersistenceDependencyMissing = errors.New("message persistent writer dependency is missing")
	ErrInvalidCommand               = errors.New("invalid message write command")
	ErrIdempotencyConflict          = errors.New("message idempotency conflict")
	ErrUniqueConstraintViolation    = errors.New("message unique constraint violation outside idempotency key")
	// ErrBatchNeedsSplit is returned before writes or after a batch transaction
	// rolled back due to an idempotency conflict or unique-key collision. Other errors,
	// especially an unknown COMMIT result, must not trigger individual retries.
	ErrBatchNeedsSplit = errors.New("message batch requires individual resolution")
)

const MaxBatchSize = 128

type Source string

const (
	SourceRealtime  Source = "realtime"
	SourceRedPacket Source = "redpacket"
)

// Command is the common input used by realtime messages and the red packet
// funds transaction. A realtime command has MessageID=0; a red packet
// command must carry the ID generated by RedPacket API.
type Command struct {
	Source      Source
	Message     messageevent.ChatMessage
	Fingerprint string
}

type Result struct {
	Message messageevent.ChatMessage
	Created bool
}

type ResultCache interface {
	Lookup(
		ctx context.Context,
		senderID int64,
		clientMessageID string,
	) (messagecache.IdempotencyEntry, bool, error)
}

// PersistentWriter owns the learning-critical M6 MySQL transaction. Its
// implementation must perform persistent idempotency, MessageID ownership
// checks, conversation_sequence locking and message insert in one transaction.
type PersistentWriter interface {
	Persist(ctx context.Context, command Command) (Result, error)
}

// BatchPersistentWriter commits a shard batch of ordinary messages together.
// Results match input order, including idempotent duplicates. No successful
// result may escape until COMMIT has succeeded. Red packet transactions use
// Persist directly so their funds and message remain in the same transaction.
type BatchPersistentWriter interface {
	PersistentWriter
	PersistBatch(ctx context.Context, commands []Command) ([]Result, error)
}

type MessageWriteService struct {
	cache  ResultCache
	writer PersistentWriter
}

func NewMessageWriteService(
	cache ResultCache,
	writer PersistentWriter,
) *MessageWriteService {
	return &MessageWriteService{cache: cache, writer: writer}
}

func (s *MessageWriteService) Send(
	ctx context.Context,
	command Command,
) (Result, error) {
	if err := ValidateCommand(command); err != nil {
		return Result{}, err
	}

	if s.cache != nil {
		entry, found, err := s.cache.Lookup(
			ctx,
			command.Message.SenderID,
			command.Message.ClientMessageID,
		)
		//与redis缓存冲突，回源数据库
		if err == nil && found {
			if entry.Fingerprint != command.Fingerprint ||
				(command.Source == SourceRedPacket &&
					entry.MessageID != command.Message.MessageID) {

				if s.writer == nil {
					return Result{}, ErrPersistenceDependencyMissing
				}
				return s.writer.Persist(ctx, command)
			}

			cachedMessage := command.Message
			cachedMessage.MessageID = entry.MessageID
			cachedMessage.Seq = entry.Seq
			return Result{Message: cachedMessage, Created: false}, nil
		}
	}

	if s.writer == nil {
		return Result{}, ErrPersistenceDependencyMissing
	}
	return s.writer.Persist(ctx, command)
}

func ValidateCommand(command Command) error {
	message := command.Message
	if message.SenderID <= 0 || message.SessionID <= 0 ||
		strings.TrimSpace(message.ClientMessageID) == "" ||
		strings.TrimSpace(command.Fingerprint) == "" {
		return ErrInvalidCommand
	}
	if message.Seq != 0 {
		return fmt.Errorf("%w: input seq must be zero", ErrInvalidCommand)
	}

	expectedFingerprint, err := messageidentity.Fingerprint(message)
	if err != nil {
		return fmt.Errorf("%w: fingerprint message: %v", ErrInvalidCommand, err)
	}
	if expectedFingerprint != command.Fingerprint {
		return fmt.Errorf("%w: fingerprint does not match message", ErrInvalidCommand)
	}

	switch command.Source {
	case SourceRealtime:
		if message.MessageID != 0 {
			return fmt.Errorf(
				"%w: realtime command cannot choose message id",
				ErrInvalidCommand,
			)
		}
		if message.MessageType == messageevent.MessageTypeRedPacket {
			return fmt.Errorf(
				"%w: realtime client cannot construct red packet message",
				ErrInvalidCommand,
			)
		}
	case SourceRedPacket:
		if message.MessageID <= 0 ||
			message.MessageType != messageevent.MessageTypeRedPacket ||
			message.Body.RedPacketID == nil ||
			*message.Body.RedPacketID <= 0 {
			return fmt.Errorf(
				"%w: red packet command requires server message and packet ids",
				ErrInvalidCommand,
			)
		}
	default:
		return fmt.Errorf("%w: unsupported source %q", ErrInvalidCommand, command.Source)
	}

	return nil
}
